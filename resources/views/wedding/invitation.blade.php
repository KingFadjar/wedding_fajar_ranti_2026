<script>
(function () {
    const audio =
        document.getElementById('wedding-music');

    const button =
        document.getElementById('wedding-music-control');

    const icon =
        document.getElementById('wedding-music-icon');

    const tip =
        document.getElementById('wedding-music-tip');

    if (!audio || !button || !icon) {
        return;
    }

    audio.volume = 0.55;

    let autoplayBlocked = false;
    let userInteracted = false;

    function updateMusicUI(isPlaying) {
        button.classList.toggle(
            'is-playing',
            isPlaying
        );

        button.setAttribute(
            'aria-pressed',
            isPlaying ? 'true' : 'false'
        );

        icon.textContent =
            isPlaying
                ? 'volume_up'
                : 'volume_off';
    }

    async function playMusic() {
        try {
            await audio.play();

            autoplayBlocked = false;
            updateMusicUI(true);

            if (tip) {
                tip.classList.remove('show');
            }

            return true;
        } catch (error) {
            autoplayBlocked = true;
            updateMusicUI(false);

            if (tip) {
                tip.classList.add('show');

                window.setTimeout(
                    function () {
                        tip.classList.remove('show');
                    },
                    4500
                );
            }

            return false;
        }
    }

    function pauseMusic() {
        audio.pause();
        updateMusicUI(false);
    }

    button.addEventListener(
        'click',
        async function () {
            userInteracted = true;

            if (audio.paused) {
                await playMusic();
            } else {
                pauseMusic();
            }
        }
    );

    audio.addEventListener(
        'play',
        function () {
            updateMusicUI(true);
        }
    );

    audio.addEventListener(
        'pause',
        function () {
            updateMusicUI(false);
        }
    );

    /*
     * Try autoplay when the invitation loads.
     * Chrome/Safari can block audible autoplay.
     */
    window.addEventListener(
        'load',
        function () {
            window.setTimeout(
                playMusic,
                350
            );
        }
    );

    /*
     * If autoplay is blocked, start on the visitor's
     * first click/touch/keyboard interaction.
     */
    async function unlockMusic() {
        if (
            userInteracted ||
            !audio.paused ||
            !autoplayBlocked
        ) {
            cleanupUnlockListeners();
            return;
        }

        userInteracted = true;

        await playMusic();

        cleanupUnlockListeners();
    }

    function cleanupUnlockListeners() {
        document.removeEventListener(
            'pointerdown',
            unlockMusic
        );

        document.removeEventListener(
            'touchstart',
            unlockMusic
        );

        document.removeEventListener(
            'keydown',
            unlockMusic
        );
    }

    document.addEventListener(
        'pointerdown',
        unlockMusic,
        { passive: true }
    );

    document.addEventListener(
        'touchstart',
        unlockMusic,
        { passive: true }
    );

    document.addEventListener(
        'keydown',
        unlockMusic
    );

    /*
     * Resume when returning to the tab if it was playing before.
     */
    let wasPlayingBeforeHidden = false;

    document.addEventListener(
        'visibilitychange',
        function () {
            if (document.hidden) {
                wasPlayingBeforeHidden =
                    !audio.paused;
            } else if (
                wasPlayingBeforeHidden
            ) {
                playMusic();
            }
        }
    );
})();
</script>


