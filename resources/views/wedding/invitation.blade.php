<script>
    (function () {

        const targetDate =
            new Date('2026-10-14T09:00:00+07:00').getTime();

        function updateTimer() {

            const now = new Date().getTime();

            const diff = targetDate - now;

            if (diff <= 0) {

                document.getElementById('countdown-days').innerText = '00';
                document.getElementById('countdown-hours').innerText = '00';
                document.getElementById('countdown-minutes').innerText = '00';
                document.getElementById('countdown-seconds').innerText = '00';

                return;
            }

            const days =
                Math.floor(
                    diff / (1000 * 60 * 60 * 24)
                );

            const hours =
                Math.floor(
                    (diff % (1000 * 60 * 60 * 24))
                    / (1000 * 60 * 60)
                );

            const minutes =
                Math.floor(
                    (diff % (1000 * 60 * 60))
                    / (1000 * 60)
                );

            const seconds =
                Math.floor(
                    (diff % (1000 * 60))
                    / 1000
                );


            const elDays =
                document.getElementById('countdown-days');

            const elHours =
                document.getElementById('countdown-hours');

            const elMinutes =
                document.getElementById('countdown-minutes');

            const elSeconds =
                document.getElementById('countdown-seconds');


            if (elDays) {
                elDays.innerText =
                    String(days).padStart(2, '0');
            }

            if (elHours) {
                elHours.innerText =
                    String(hours).padStart(2, '0');
            }

            if (elMinutes) {
                elMinutes.innerText =
                    String(minutes).padStart(2, '0');
            }

            if (elSeconds) {
                elSeconds.innerText =
                    String(seconds).padStart(2, '0');
            }
        }


        updateTimer();

        setInterval(
            updateTimer,
            1000
        );

    })();


